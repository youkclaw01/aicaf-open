from interview_question_details import QUESTION_DETAILS


def questions_for(track):
    """유형별 문항을 반환한다. 기존 ID·소속·필수 여부를 보존하고 보조 정보는 복사한다."""
    from copy import deepcopy
    out = []
    for code, aname, topics in FRAMEWORKS[track]:
        for tcode, tname, qs in topics:
            for n, (q, point, top, must, ev) in enumerate(qs, 1):
                qid = f"{tcode}-{n}"
                row = dict(id=qid, area=code, area_name=aname, topic=tcode, topic_name=tname,
                           question=q, point=point, top=top, must=must == "필수", evidence=ev)
                detail = deepcopy(QUESTION_DETAILS.get(qid, {}))
                row.update(interviewer_note=detail.get("interviewer_note", point),
                           terms=detail.get("terms", []), followups=detail.get("followups", []),
                           cost_inputs=detail.get("cost_inputs", []),
                           display_area_name=detail.get("display_area_name", aname),
                           display_topic_name=detail.get("display_topic_name", tname))
                out.append(row)
    return out
